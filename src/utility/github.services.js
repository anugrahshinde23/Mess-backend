import fs from "fs";
import axios from "axios";
import { execSync } from "child_process";

export const createGithubRepo = async (repoName) => {
  const response = await axios.post(
    "https://api.github.com/user/repos",
    {
      name: repoName,
      private: false,
    },
    {
      headers: {
        Authorization: `token ${process.env.GITHUB_TOKEN}`,
        Accept: "application/vnd.github+json",
      },
    }
  );

  return response.data.clone_url;
};

export const pushToGithub = async (projectRoot, repoUrl) => {
  // ✅ Initialize git only if not exists
  if (!fs.existsSync(`${projectRoot}/.git`)) {
    execSync("git init", { cwd: projectRoot });
  }

  // ✅ Set local git identity
  execSync('git config user.email "bot@verityapp.com"', {
    cwd: projectRoot,
  });
  execSync('git config user.name "Verity Bot"', {
    cwd: projectRoot,
  });

  // ✅ Add all files
  execSync("git add .", { cwd: projectRoot });

  // ✅ Allow empty commit (safe)
  execSync('git commit -m "Project generated by Verity AI" --allow-empty', {
    cwd: projectRoot,
  });

  // ✅ Ensure main branch
  execSync("git branch -M main", { cwd: projectRoot });

  // ✅ Remove existing remote if exists
  try {
    execSync("git remote remove origin", { cwd: projectRoot });
  } catch (e) {
    // ignore if not exists
  }

  execSync(`git remote add origin ${repoUrl}`, { cwd: projectRoot });

  // ✅ Push
  execSync("git push -u origin main", { cwd: projectRoot });

  console.log("Code pushed successfully 🚀");
};